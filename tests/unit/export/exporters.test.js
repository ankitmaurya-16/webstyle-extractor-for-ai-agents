import { describe, expect, it } from 'vitest';
import { runInNewContext } from 'node:vm';
import { unzipSync, strFromU8 } from 'fflate';
import { analyze } from '../../../src/analyze/index.js';
import {
  EXPORT_FILES,
  downloadName,
  exportCssVars,
  exportDesignMd,
  exportDtcg,
  exportFile,
  exportTailwindV3,
  exportTailwindV4,
  exportZip,
  zipName,
} from '../../../src/export/index.js';
import { EXPORT_FORMATS } from '../../../src/model/types.js';
import { FIXTURE_NAMES, loadRaw } from '../helpers.js';

const VERSION = '1.0.0';
const designs = Object.fromEntries(FIXTURE_NAMES.map((n) => [n, analyze(loadRaw(n))]));

describe.each(FIXTURE_NAMES)('exporters on %s', (name) => {
  const design = designs[name];

  it.each(EXPORT_FORMATS)('AC-F7.8 %s matches its snapshot', async (format) => {
    const text = exportFile(format, design, VERSION);
    await expect(text).toMatchFileSnapshot(`./__snapshots__/${name}/${EXPORT_FILES[format]}`);
  });

  it('AC-F7.8 is byte-identical for the same design', () => {
    for (const format of EXPORT_FORMATS) {
      expect(exportFile(format, structuredClone(design), VERSION)).toBe(
        exportFile(format, design, VERSION),
      );
    }
    expect(exportZip(design, VERSION)).toEqual(exportZip(structuredClone(design), VERSION));
  });

  it('AC-F7.7 DESIGN.md stays under 300 lines', () => {
    expect(exportDesignMd(design, VERSION).split('\n').length).toBeLessThan(300);
  });

  it('follows the shared file rules: LF, trailing newline, generated-by header, lowercase hex', () => {
    for (const format of EXPORT_FORMATS) {
      const text = exportFile(format, design, VERSION);
      expect(text.endsWith('\n') && !text.endsWith('\n\n'), format).toBe(true);
      expect(text, format).not.toContain('\r');
      expect(text, format).toMatch(/WebStyle Extractor v1\.0\.0/);
      expect(text, format).toContain('2026-10-18');
      expect(text, format).not.toMatch(/#[0-9a-f]*[A-F][0-9a-fA-F]*\b/);
    }
  });

  it('tokens.json is valid JSON with DTCG value shapes', () => {
    const json = JSON.parse(exportDtcg(design, VERSION));
    expect(json.$description).toMatch(/^Generated by WebStyle Extractor/);
    for (const [key, token] of Object.entries(json.color ?? {})) {
      if (typeof token.$value === 'string') {
        expect(token.$value, key).toMatch(/^\{color\.[a-z0-9-]+\}$/);
      } else {
        expect(token.$value.colorSpace).toBe('srgb');
        expect(token.$value.components).toHaveLength(3);
        expect(token.$value.hex).toMatch(/^#[0-9a-f]{6}$/);
      }
    }
    for (const group of ['space', 'radius', 'text', 'breakpoint']) {
      for (const token of Object.values(json[group] ?? {})) {
        expect(token).toMatchObject({ $type: 'dimension', $value: { unit: 'px' } });
      }
    }
    for (const token of Object.values(json.shadow ?? {})) {
      const layers = Array.isArray(token.$value) ? token.$value : [token.$value];
      for (const layer of layers)
        expect(Object.keys(layer)).toEqual(
          expect.arrayContaining(['color', 'offsetX', 'offsetY', 'blur', 'spread']),
        );
    }
  });
});

describe('export details', () => {
  const classic = designs.classic;

  it('AC-F7.1 offers the five formats', () => {
    expect(Object.values(EXPORT_FILES)).toEqual([
      'DESIGN.md',
      'tokens.json',
      'theme.css',
      'tailwind.config.js',
      'variables.css',
    ]);
  });

  it('DESIGN.md has the agent rules and the sections', () => {
    const md = exportDesignMd(classic, VERSION);
    expect(md).toMatch(/^# Design system: 127\.0\.0\.1\n/);
    expect(md).toContain('1. Use only the tokens in this file.');
    expect(md).toContain('3. Spacing uses a 4px base unit.');
    for (const h of [
      '## Colors',
      '### Semantic',
      '### Scales',
      '## Typography',
      '## Spacing',
      '## Radius',
      '## Shadows',
      '## Breakpoints',
      '## Components',
      '## Notes',
    ]) {
      expect(md).toContain(h);
    }
    expect(md).toContain('background primary (blue-600), text white');
  });

  it('DESIGN.md omits rule 3 without a base unit and renumbers', () => {
    const md = exportDesignMd(
      { ...classic, spacing: { baseUnitPx: null, tokens: classic.spacing.tokens } },
      VERSION,
    );
    expect(md).not.toContain('base unit. Use the spacing scale');
    expect(md).toMatch(/\n3\. Body text is/);
  });

  it('AC-F4.6 DESIGN.md marks breakpoints partial and says when none were readable', () => {
    const md = exportDesignMd(designs['cross-origin'], VERSION);
    expect(md).toContain('Breakpoints are partial: 1 of 2 stylesheets could not be read.');
    const none = {
      ...classic,
      breakpoints: [],
      meta: {
        ...classic.meta,
        partial: ['breakpoints', 'cssVariables'],
        stylesheets: { readable: 0, unreadable: 1 },
      },
    };
    const text = exportDesignMd(none, VERSION);
    expect(text).toContain('Not readable on this site.');
    expect(text).toContain('no stylesheet on this page could be read');
  });

  it('notes truncation from the element cap', () => {
    expect(exportDesignMd(designs.large, VERSION)).toContain('stopped at the element limit');
  });

  it('theme.css puts scales in @theme and semantic aliases in @theme inline', () => {
    const css = exportTailwindV4(classic, VERSION);
    expect(css).toContain('@theme {');
    expect(css).toContain('  --color-blue-600: #2563eb;');
    expect(css).toContain('  --spacing: 4px;');
    expect(css).toContain('@theme inline {\n  --color-background: var(--color-white);');
    expect(css).toContain('--text-base--line-height: 24px;');
  });

  it('theme.css lists raw spacing in a comment without a base unit', () => {
    const css = exportTailwindV4(
      { ...classic, spacing: { baseUnitPx: null, tokens: classic.spacing.tokens } },
      VERSION,
    );
    expect(css).not.toContain('--spacing:');
    expect(css).toMatch(/\/\* Spacing values \(no base unit\): 4px, 8px/);
  });

  it('tailwind.config.js extends the theme with grouped scales and resolved semantic hex', () => {
    const js = exportTailwindV3(classic, VERSION);
    expect(js).toContain('module.exports = {\n  theme: {\n    extend: {');
    expect(js).toContain("gray: { 200: '#e5e7eb'");
    expect(js).toContain("primary: '#2563eb',");
    expect(js).toContain("'text-muted': '#6b7280',");
    expect(js).toContain("base: ['16px', { lineHeight: '24px' }],");
    // It must be valid JavaScript.
    const module = { exports: {} };
    runInNewContext(js, { module });
    expect(module.exports.theme.extend.colors.blue[600]).toBe('#2563eb');
  });

  it('variables.css declares every token on :root', () => {
    const css = exportCssVars(classic, VERSION);
    expect(css).toMatch(
      /^\/\* Generated by WebStyle Extractor v1\.0\.0 from http:\/\/127\.0\.0\.1:4173\/classic\.html on 2026-10-18 \*\/\n:root \{/,
    );
    expect(css).toContain('--color-text: var(--color-gray-900);');
    expect(css).toContain('--space-4: 16px;');
    expect(css).toContain('--breakpoint-md: 768px; /* reference only');
  });

  it('AC-F7.4 names downloads <hostname>-<filename>', () => {
    expect(downloadName(classic, 'design-md')).toBe('127.0.0.1-DESIGN.md');
    expect(downloadName(classic, 'tailwind-v3')).toBe('127.0.0.1-tailwind.config.js');
  });

  it('AC-F7.5 zips all five files as <hostname>-webstyle.zip', () => {
    expect(zipName(classic)).toBe('127.0.0.1-webstyle.zip');
    const files = unzipSync(exportZip(classic, VERSION));
    expect(Object.keys(files).sort()).toEqual([
      'DESIGN.md',
      'tailwind.config.js',
      'theme.css',
      'tokens.json',
      'variables.css',
    ]);
    expect(strFromU8(files['DESIGN.md'])).toBe(exportDesignMd(classic, VERSION));
  });

  it('AC-F7.6 excluded tokens never appear in any export', () => {
    const d = structuredClone(classic);
    for (const c of d.colors) if (c.name === 'red-100') c.excluded = true;
    for (const r of d.radii) if (r.name === 'radius-sm') r.excluded = true;
    for (const format of EXPORT_FORMATS) {
      const text = exportFile(format, d, VERSION);
      expect(text, format).not.toContain('#fee2e2');
      expect(text, format).not.toMatch(
        /radius-sm|radius\.sm|"sm": \{\s+"\$type": "dimension",\s+"\$value": \{\s+"value": 4/,
      );
    }
  });

  it('never writes a self-referencing semantic alias', () => {
    const d = structuredClone(classic);
    const blue = d.colors.find((c) => c.name === 'blue-600');
    blue.name = 'primary';
    for (const r of d.components)
      for (const v of Object.values(r.styles)) if (v?.id === blue.id) v.ref = 'color.primary';
    expect(exportTailwindV4(d, VERSION)).not.toContain('--color-primary: var(--color-primary)');
    expect(exportCssVars(d, VERSION)).not.toContain('--color-primary: var(--color-primary)');
    expect(JSON.parse(exportDtcg(d, VERSION)).color.primary.$value).toMatchObject({
      hex: '#2563eb',
    });
  });
});
