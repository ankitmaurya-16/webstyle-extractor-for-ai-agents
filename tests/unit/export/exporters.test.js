import { describe, expect, it } from 'vitest';
import { runInNewContext } from 'node:vm';
import { strFromU8, unzipSync } from 'fflate';
import {
  EXPORT_LABELS,
  FILE_MAP,
  downloadName,
  exportDesignMd,
  exportFile,
  exportFiles,
  exportZip,
  renderFormat,
  zipName,
} from '../../../src/export/index.js';
import { EXPORT_FORMATS } from '../../../src/model/types.js';
import { FIXTURE_NAMES } from '../helpers.js';
import { VERSION, fixtureDesigns, lineCount, richDesign } from './designs.js';

const designs = {
  ...fixtureDesigns(),
  rich: richDesign(),
  'rich-media': richDesign({ mechanism: 'media' }),
};
const SNAPSHOT_DESIGNS = [...FIXTURE_NAMES, 'rich', 'rich-media'];

/** Runs a Tailwind v3 config file and returns its exports. */
const runConfig = (text) => {
  const module = { exports: {} };
  runInNewContext(text, { module });
  return module.exports;
};

describe.each(SNAPSHOT_DESIGNS)('exporters on %s', (name) => {
  const design = designs[name];

  it.each(EXPORT_FORMATS)('AC-F7.8 %s matches its snapshots', async (format) => {
    for (const file of renderFormat(format, design, VERSION)) {
      await expect(file.text).toMatchFileSnapshot(`./__snapshots__/${name}/${file.path}`);
    }
  });

  it('AC-F7.8 is byte-identical for the same design', () => {
    for (const format of EXPORT_FORMATS) {
      expect(exportFile(format, structuredClone(design), VERSION), format).toBe(
        exportFile(format, design, VERSION),
      );
    }
    expect(exportZip(design, VERSION)).toEqual(exportZip(structuredClone(design), VERSION));
  });

  it('follows the rules for all formats: LF, one trailing newline, lowercase hex, UTC date', () => {
    for (const file of exportFiles(design, VERSION)) {
      expect(file.text.endsWith('\n') && !file.text.endsWith('\n\n'), file.path).toBe(true);
      expect(file.text, file.path).not.toContain('\r');
      expect(file.text, file.path).not.toMatch(/#[0-9a-f]*[A-F][0-9a-fA-F]*\b(?![-\w])/);
      // prompt.md and the CLAUDE.md block are pasted as they are, so they carry no date.
      if (
        !['CLAUDE.md', 'design/prompt.md', '.cursor/rules/design-system.mdc'].includes(file.path)
      ) {
        expect(file.text, file.path).toMatch(/2026-10-1[0-9]/);
      }
    }
  });

  it('writes a generated-by header in every file that has room for one', () => {
    const headerless = new Set([
      'DESIGN.md',
      'design/prompt.md',
      'AGENTS.md',
      'CLAUDE.md',
      '.cursor/rules/design-system.mdc',
      'design/audit.md',
      'design/styleguide.html',
    ]);
    for (const file of exportFiles(design, VERSION)) {
      if (headerless.has(file.path)) continue;
      expect(file.text, file.path).toMatch(
        /Generated by WebStyle Extractor v2\.0\.0 from \S+ on \d{4}-\d{2}-\d{2}/,
      );
    }
    expect(exportFile('design-md', design, VERSION)).toMatch(/· WebStyle Extractor v2\.0\.0\n/);
  });

  it('spec 9.1 DESIGN.md stays under 450 lines', () => {
    expect(lineCount(exportDesignMd(design, VERSION))).toBeLessThanOrEqual(450);
  });

  it('spec 9.5 DESIGN.md sections come in the documented order', () => {
    const order = [
      'Rules for the agent',
      'Stack',
      'Colors',
      'Typography',
      'Spacing',
      'Layout',
      'Radius',
      'Borders',
      'Shadows',
      'Opacity',
      'Z-index',
      'Motion',
      'Breakpoints',
      'Responsive',
      'Components',
      'Accessibility',
      'Values not in your system',
      'Notes',
    ];
    const headings = [...exportDesignMd(design, VERSION).matchAll(/^## (.+)$/gm)].map((m) => m[1]);
    expect(headings.length).toBeGreaterThan(3);
    for (const h of headings) expect(order, h).toContain(h);
    const positions = headings.map((h) => order.indexOf(h));
    expect(positions).toEqual([...positions].sort((a, b) => a - b));
    expect(headings[0]).toBe('Rules for the agent');
    expect(headings.at(-1)).toBe('Notes');
  });

  it('spec 9.5 DESIGN.md subsections follow the order within Colors and Components', () => {
    const md = exportDesignMd(design, VERSION);
    const sub = (section) => {
      const body = md.split(`## ${section}\n`)[1]?.split(/\n## /)[0] ?? '';
      return [...body.matchAll(/^### (.+)$/gm)].map((m) => m[1]);
    };
    const colors = sub('Colors').map((h) =>
      ['Semantic', 'Scales', 'Translucent', 'Gradients'].indexOf(h),
    );
    expect(colors).toEqual([...colors].sort((a, b) => a - b));
    expect(colors).not.toContain(-1);
    const components = sub('Components');
    if (components.length) expect(components[0]).toBe('Focus ring');
  });

  it('spec 9.1 exports are always English', () => {
    for (const file of exportFiles(design, VERSION)) {
      // Every word outside page-derived values is ASCII; the analysis never translates.
      expect(file.text, file.path).not.toMatch(/[À-ɏЀ-ӿ぀-ヿ一-鿿]/);
    }
    expect(exportDesignMd(design, VERSION)).toContain('## Rules for the agent');
  });

  it('tokens.json is valid JSON with DTCG value shapes', () => {
    const json = JSON.parse(exportFile('dtcg', design, VERSION));
    expect(json.$description).toMatch(/^Generated by WebStyle Extractor/);
    for (const [key, token] of Object.entries(json.color ?? {})) {
      expect(token.$type, key).toBe('color');
      expect(token.$value.colorSpace).toBe('srgb');
      expect(token.$value.components).toHaveLength(3);
      expect(token.$value.hex).toMatch(/^#[0-9a-f]{6}$/);
    }
    for (const token of Object.values(json.semantic ?? {}))
      expect(token.$value).toMatch(/^\{color\.[a-z0-9-]+\}$/);
    for (const group of ['space', 'radius', 'text', 'breakpoint', 'container', 'border-width']) {
      for (const token of Object.values(json[group] ?? {})) {
        expect(token).toMatchObject({ $type: 'dimension', $value: { unit: 'px' } });
      }
    }
    for (const token of Object.values(json.shadow ?? {})) {
      const layers = Array.isArray(token.$value) ? token.$value : [token.$value];
      for (const layer of layers)
        expect(Object.keys(layer)).toEqual(
          expect.arrayContaining(['color', 'offsetX', 'offsetY', 'blur', 'spread']),
        );
    }
  });

  it('tailwind.webstyle.js runs as a CommonJS config with theme.extend', () => {
    const config = runConfig(exportFile('tailwind-v3', design, VERSION));
    expect(Object.keys(config)).toEqual(expect.arrayContaining(['theme']));
    expect(config.theme.extend).toBeTypeOf('object');
    expect(Object.keys(config.theme)).toEqual(['extend']);
  });
});

describe('file map and zip (spec 9.2)', () => {
  const design = designs.rich;

  it('AC-F32.6 every format has a label and lands at its default path', () => {
    expect(Object.keys(FILE_MAP).sort()).toEqual([...EXPORT_FORMATS].sort());
    expect(Object.keys(EXPORT_LABELS).sort()).toEqual([...EXPORT_FORMATS].sort());
    expect(FILE_MAP).toMatchObject({
      'design-md': ['DESIGN.md'],
      prompt: ['design/prompt.md'],
      dtcg: ['design/tokens.json', 'design/tokens.dark.json'],
      'tailwind-v4': ['design/theme.css'],
      'tailwind-v3': ['design/tailwind.webstyle.js'],
      'css-vars': ['design/variables.css'],
      shadcn: ['design/shadcn-theme.css'],
      styleguide: ['design/styleguide.html'],
      'agents-md': ['AGENTS.md'],
      'cursor-rules': ['.cursor/rules/design-system.mdc'],
      'claude-md': ['CLAUDE.md'],
      audit: ['design/audit.md'],
    });
  });

  it('the zip holds every format at its file-map path and is named after the host', () => {
    const files = unzipSync(exportZip(design, VERSION));
    const expected = EXPORT_FORMATS.flatMap((f) =>
      renderFormat(f, design, VERSION).map((x) => x.path),
    );
    expect(Object.keys(files).sort()).toEqual([...expected].sort());
    expect(strFromU8(files['DESIGN.md'])).toBe(exportFile('design-md', design, VERSION));
    expect(Object.keys(files)).toContain('design/tailwind.webstyle.js');
    expect(Object.keys(files)).not.toContain('tailwind.config.js');
    expect(zipName(design)).toBe('127.0.0.1-webstyle.zip');
  });

  it('the zip holds only the selected formats', () => {
    const files = unzipSync(exportZip(design, VERSION, { formats: ['design-md', 'prompt'] }));
    expect(Object.keys(files).sort()).toEqual(['DESIGN.md', 'design/prompt.md']);
  });

  it('single-file downloads keep the <hostname>-<file> naming', () => {
    expect(downloadName(design, 'design-md')).toBe('127.0.0.1-DESIGN.md');
    expect(downloadName(design, 'tailwind-v3')).toBe('127.0.0.1-tailwind.webstyle.js');
    expect(downloadName(design, 'cursor-rules')).toBe('127.0.0.1-design-system.mdc');
  });

  it('a single-theme design writes no tokens.dark.json and no dark Figma mode', () => {
    const paths = exportFiles(designs.classic, VERSION).map((f) => f.path);
    expect(paths).not.toContain('design/tokens.dark.json');
    expect(paths).not.toContain('design/figma/Semantic.Dark.tokens.json');
    expect(paths).toContain('design/tokens.json');
  });

  it('unknown formats are a programmer error', () => {
    expect(() => renderFormat('pdf', design, VERSION)).toThrow(/Unknown export format/);
  });
});

describe('spec 9.3 paired themes in each format', () => {
  const classDesign = designs.rich;
  const mediaDesign = designs['rich-media'];
  const file = (format, d = classDesign, index = 0) => renderFormat(format, d, VERSION)[index].text;

  it('the rich design has two themes with a class mechanism', () => {
    expect(classDesign.meta.modes).toEqual(['light', 'dark']);
    expect(classDesign.meta.themeMechanism).toBe('class');
    expect(mediaDesign.meta.themeMechanism).toBe('media');
  });

  it('DESIGN.md has Light and Dark columns and a Theme switching line', () => {
    const md = file('design-md');
    expect(md).toMatch(/\| Role +\| Light token +\| Light +\| Dark token +\| Dark +\|/);
    expect(md).toMatch(/\| primary +\| blue-600 +\| #2563eb \| blue-400 +\| #60a5fa \|/);
    expect(md).toContain('Theme switching: the `.dark` class on `<html>`');
    expect(file('design-md', mediaDesign)).toContain(
      'Theme switching: the `prefers-color-scheme` media query',
    );
  });

  it('tokens.dark.json holds only dark semantic aliases to primitives in tokens.json', () => {
    const [light, dark] = renderFormat('dtcg', classDesign, VERSION).map((f) => JSON.parse(f.text));
    expect(Object.keys(dark)).toEqual(['$description', 'semantic']);
    expect(dark.$description).toMatch(/load together with tokens\.json/);
    expect(dark.semantic.primary.$value).toBe('{color.blue-400}');
    expect(light.semantic.primary.$value).toBe('{color.blue-600}');
    for (const token of Object.values(dark.semantic)) {
      const key = token.$value.slice('{color.'.length, -1);
      expect(light.color[key], key).toBeDefined();
    }
  });

  it('theme.css puts primitives in @theme, semantics in :root and .dark, and maps them inline', () => {
    const css = file('tailwind-v4');
    expect(css).toContain('@custom-variant dark (&:where(.dark, .dark *));');
    expect(css).toMatch(/@theme \{\n {2}--color-white: #ffffff;/);
    expect(css).toMatch(/:root \{[^}]*--primary: var\(--color-blue-600\);/);
    expect(css).toMatch(/\.dark \{[^}]*--primary: var\(--color-blue-400\);/);
    expect(css).toMatch(/@theme inline \{[^}]*--color-primary: var\(--primary\);/);
    const media = file('tailwind-v4', mediaDesign);
    expect(media).not.toContain('@custom-variant');
    expect(media).toMatch(
      /@media \(prefers-color-scheme: dark\) \{\n {2}:root \{[^}]*--primary: var\(--color-blue-400\);/,
    );
  });

  it('tailwind.webstyle.js sets darkMode and writes semantic colors as variables', () => {
    const text = file('tailwind-v3');
    expect(text).toMatch(/import design\/variables\.css/);
    const config = runConfig(text);
    expect(config.darkMode).toEqual(['selector', '.dark']);
    expect(config.theme.extend.colors.primary).toBe('var(--color-primary)');
    expect(runConfig(file('tailwind-v3', mediaDesign)).darkMode).toBe('media');
    expect(runConfig(exportFile('tailwind-v3', designs.classic, VERSION)).darkMode).toBeUndefined();
  });

  it('variables.css writes dark semantics in the site selector or the media query', () => {
    expect(file('css-vars')).toMatch(/\n\.dark \{\n[^}]*--color-primary: var\(--color-blue-400\);/);
    expect(file('css-vars', mediaDesign)).toMatch(
      /@media \(prefers-color-scheme: dark\) \{\n {2}:root \{\n[^}]* {4}--color-primary: var\(--color-blue-400\);/,
    );
  });

  it('shadcn-theme.css always uses :root and .dark', () => {
    expect(file('shadcn')).toMatch(/:root \{[\s\S]*\n\.dark \{/);
    expect(file('shadcn', mediaDesign)).toMatch(/\n\.dark \{/);
  });

  it('styleguide.html has a Light / Dark toggle', () => {
    expect(file('styleguide')).toContain('id="theme"');
  });

  it('Figma has Light and Dark modes in the Semantic collection', () => {
    const files = renderFormat('figma', classDesign, VERSION);
    expect(files.map((f) => f.path)).toEqual(FILE_MAP.figma);
  });

  it('prompt.md writes each semantic color as light / dark', () => {
    expect(file('prompt')).toMatch(
      /Colors \(light \/ dark\): background #ffffff \/ #0b0f19 · text #111827 \/ #ffffff/,
    );
    expect(file('prompt')).toContain('primary #2563eb / #60a5fa');
  });
});

describe('spec 9.4 new token categories in each format', () => {
  const d = designs.rich;
  const file = (format) => exportFile(format, d, VERSION);

  it('the rich design has every new category', () => {
    expect(d.gradients.length).toBeGreaterThan(0);
    expect(d.motion.durations.map((x) => x.ms)).toEqual([150, 300]);
    expect(d.motion.easings[0].name).toBe('ease-out');
    expect(d.zIndex[0]).toMatchObject({ name: 'z-dialog', value: 50 });
    expect(d.opacities[0]).toMatchObject({ name: 'opacity-disabled', value: 0.5 });
    expect(d.layout.gridColumns[0].value).toBe(3);
    expect(d.focusRing.source).toBe('forced');
  });

  it('DESIGN.md has a section or line for each category', () => {
    const md = file('design-md');
    expect(md).toContain('### Gradients');
    expect(md).toContain('### Text styles');
    expect(md).toContain('Letter spacing: tracking-normal 0em');
    expect(md).toMatch(
      /## Layout\n\n- Containers: container-sm \(verify\) 1024px\n- Grid columns: 3 \(100%\)\n- Gaps: gap-20 20px/,
    );
    expect(md).toContain('## Borders\n\nborder-1 1px · usually solid');
    expect(md).toContain('## Opacity\n\nopacity-disabled 0.5');
    expect(md).toContain('## Z-index\n\nz-dialog 50');
    expect(md).toMatch(
      /## Motion\n\nduration-150, duration-300 · ease-out cubic-bezier\(0, 0, 0\.2, 1\)/,
    );
    expect(md).toContain(
      '### Focus ring\n\noutline 2px solid focus-ring (blue-600), offset 2px (from forced states)',
    );
    expect(md).toContain('## Stack\n\n- Web font: Helvetica Neue 400, 600 (self-hosted)');
    expect(md).toMatch(/\| hover +\| background gray-900/);
  });

  it('tokens.json uses the DTCG types for each category', () => {
    const json = JSON.parse(file('dtcg'));
    expect(json.gradient['1']).toMatchObject({
      $type: 'gradient',
      $extensions: { 'com.webstyle': { direction: '135deg' } },
    });
    expect(json.gradient['1'].$value.map((s) => s.color)).toEqual([
      '{color.blue-600}',
      '{color.blue-400}',
    ]);
    expect(json.typography.h1.$type).toBe('typography');
    expect(json.tracking.normal.$extensions['com.webstyle'].unit).toBe('em');
    expect(json.container.sm).toMatchObject({
      $type: 'dimension',
      $value: { value: 1024, unit: 'px' },
    });
    expect(json['grid-columns']['3']).toEqual({ $type: 'number', $value: 3 });
    expect(json.gap['20'].$type).toBe('dimension');
    expect(json['border-width']['1'].$type).toBe('dimension');
    expect(json.opacity.disabled).toEqual({ $type: 'number', $value: 0.5 });
    expect(json['z-index'].dialog).toEqual({ $type: 'number', $value: 50 });
    expect(json.duration['150']).toEqual({ $type: 'duration', $value: { value: 150, unit: 'ms' } });
    expect(json.easing.out).toEqual({ $type: 'cubicBezier', $value: [0, 0, 0.2, 1] });
    expect(json.font.sans.$extensions['com.webstyle'].provider).toBe('self-hosted');
    expect(
      json.$extensions['com.webstyle'].recipes['component:button:primary'].byMode.light.hover,
    ).toBeDefined();
    expect(json.$extensions['com.webstyle'].focusRing.source).toBe('forced');
  });

  it('theme.css uses namespaces where Tailwind v4 has them and :root otherwise', () => {
    const css = file('tailwind-v4');
    const theme = css.split('@theme {')[1].split('\n}')[0];
    const root = css.split(':root {')[1].split('\n}')[0];
    for (const v of [
      '--tracking-normal: 0em',
      '--container-sm: 1024px',
      '--ease-out: cubic-bezier(0, 0, 0.2, 1)',
      '--font-sans:',
    ]) {
      expect(theme, v).toContain(v);
    }
    expect(theme).toContain('/* web font: self-hosted */');
    for (const v of [
      '--z-dialog: 50',
      '--opacity-disabled: 0.5',
      '--duration-150: 150ms',
      '--border-1: 1px',
      '--gap-20: 20px',
      '--gradient-1: linear-gradient(135deg, var(--color-blue-600), var(--color-blue-400))',
    ]) {
      expect(root, v).toContain(v);
      expect(theme, v).not.toContain(v);
    }
    expect(css).toMatch(
      /@utility text-h1 \{\n {2}font-family: var\(--font-display\);\n {2}font-size: 36px;/,
    );
    expect(css).not.toContain('grid-3');
  });

  it('tailwind.webstyle.js puts each category in its theme key', () => {
    const extend = runConfig(file('tailwind-v3')).theme.extend;
    expect(extend.backgroundImage['1']).toBe('linear-gradient(135deg, #2563eb, #60a5fa)');
    expect(extend.fontSize.h1).toEqual(['36px', { lineHeight: '40px', fontWeight: '700' }]);
    expect(extend.letterSpacing.normal).toBe('0em');
    expect(extend.maxWidth.sm).toBe('1024px');
    expect(extend.gap['20']).toBe('20px');
    expect(extend.borderWidth['1']).toBe('1px');
    expect(extend.opacity.disabled).toBe('0.5');
    expect(extend.zIndex.dialog).toBe('50');
    expect(extend.transitionDuration['150']).toBe('150ms');
    expect(extend.transitionTimingFunction.out).toBe('cubic-bezier(0, 0, 0.2, 1)');
    expect(extend.ringColor.DEFAULT).toBe('#2563eb');
    expect(extend.ringWidth.DEFAULT).toBe('2px');
    expect(extend.ringOffsetWidth.DEFAULT).toBe('2px');
  });

  it('variables.css writes a custom property per category', () => {
    const css = file('css-vars');
    for (const v of [
      '--gradient-1:',
      '--text-h1-font-size: 36px',
      '--tracking-normal: 0em',
      '--container-sm: 1024px',
      '--gap-20: 20px',
      '--border-1: 1px',
      '--opacity-disabled: 0.5',
      '--z-dialog: 50',
      '--duration-150: 150ms',
      '--ease-out:',
      '--focus-ring-outline: 2px solid #2563eb',
      '--focus-ring-offset: 2px',
      '--font-sans:',
    ]) {
      expect(css, v).toContain(v);
    }
  });

  it('translucent colors are 8-digit hex and `/` becomes `-a` in CSS names', () => {
    const dark = designs.dark;
    const translucent = dark.colors.find((c) => c.alpha < 1);
    expect(translucent.name).toBe('black/50');
    expect(exportFile('tailwind-v4', dark, VERSION)).toContain('--color-black-a50: #00000080;');
    expect(exportFile('css-vars', dark, VERSION)).toContain('--color-black-a50: #00000080;');
    expect(
      runConfig(exportFile('tailwind-v3', dark, VERSION)).theme.extend.colors['black/50'],
    ).toBe('#00000080');
    expect(JSON.parse(exportFile('dtcg', dark, VERSION)).color['black-a50'].$value.alpha).toBe(
      0.502,
    );
    expect(exportDesignMd(dark, VERSION)).toMatch(/### Translucent\n\n\| Token +\| Value +\|/);
  });
});
